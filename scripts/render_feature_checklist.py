#!/usr/bin/env python3
"""Render the feature checklist from definitions and role-owned evidence files."""
from pathlib import Path
import csv
import json
from check_backend_review import validate_review, safe_path, digest, read_json, ReviewError

ROOT = Path(__file__).resolve().parents[1]
rows = list(csv.DictReader((ROOT / 'docs/features.tsv').open(), delimiter='\t'))
ids = {r['id'] for r in rows}
assert len(ids) == len(rows), 'Duplicate feature ID'
for row in rows:
    assert set(filter(None, row['depends_on'].split(','))) <= ids, row['id']

review_required = {}
backend_reviews = {}
handoff_records = {}


def verified(role, feature):
    relative = f'docs/handoffs/{role}/{feature}.json'
    try:
        path = safe_path(ROOT, relative)
        data = read_json(path)
        if data.get('status') != 'verified':
            return False
        if not data.get('summary') or not data.get('evidence'):
            return False
        for evidence in data['evidence']:
            if not all(evidence.get(k) for k in ('command', 'result', 'environment', 'path')):
                return False
            evidence_path = safe_path(ROOT, evidence['path'])
            # Downstream evidence must bind current bytes, not just a surviving filename.
            if role != 'backend' and (evidence_path.stat().st_size == 0 or
                                      evidence.get('sha256') != digest(evidence_path)):
                return False
        if role == 'backend':
            if not data.get('api_contract') or data.get('limitations') is None:
                return False
            review = data.get('reviewPath')
            result = validate_review(review, root=ROOT, feature_id=feature) if isinstance(review, str) else None
            if result is None or not result.passed:
                review_required[feature] = '; '.join(result.errors) if result else 'No independent reviewPath'
                return False
            backend_reviews[feature] = digest(safe_path(ROOT, review))
        handoff_records[role, feature] = data
        return True
    except (ReviewError, OSError, ValueError, TypeError, KeyError, AttributeError, ArithmeticError, RecursionError):
        return False


done = {(role, r['id']): verified(role, r['id']) for r in rows for role in ('backend', 'ui', 'integration')}
dependencies = {r['id']: list(filter(None, r['depends_on'].split(','))) for r in rows}


def backend_ready(feature, visiting=None):
    # All transitive backend prerequisites must pass; cycles fail closed.
    visiting = set() if visiting is None else visiting
    if feature in visiting or not done['backend', feature]:
        return False
    return all(backend_ready(dep, visiting | {feature}) for dep in dependencies[feature])


for row in rows:
    fid = row['id']
    review_digest = backend_reviews.get(fid)
    for role in ('ui', 'integration'):
        data = handoff_records.get((role, fid), {})
        if not backend_ready(fid) or data.get('backendReviewSHA256') != review_digest:
            done[role, fid] = False
    if row['ui_required'] == 'yes':
        integration = handoff_records.get(('integration', fid), {})
        ui_path = ROOT / 'docs/handoffs/ui' / f'{fid}.json'
        if not done['ui', fid] or integration.get('uiHandoffSHA256') != digest(ui_path):
            done['integration', fid] = False

lines = ['# Feature delivery checklist', '',
    'Generated by `python3 scripts/render_feature_checklist.py`. Definitions: [features.tsv](features.tsv). Detailed behavior: [FEATURE_SPEC.md](FEATURE_SPEC.md). Delivery rules: [handoffs/README.md](handoffs/README.md).', '',
    'B = Backend independently reviewed and verified; U = UI verified; I = integrated acceptance. A design or template artifact does not check an application delivery box. UI implementation starts only after its backend contract and prerequisites are verified; visual planning may proceed earlier. `n/a` means no user-facing UI for that control.', '',
    f'Total: **{len(rows)} features**. Backend verified: **{sum(done["backend", r["id"]] for r in rows)}**. UI verified: **{sum(done["ui", r["id"]] for r in rows)}**. Integrated: **{sum(done["integration", r["id"]] for r in rows)}**.', '']
if review_required:
    lines += ['Backend handoffs with **review required** (historical evidence preserved; dependent UI/integration approval withheld): ' + ', '.join(sorted(review_required)) + '.', '']
for area in dict.fromkeys(r['area'] for r in rows):
    lines += [f'## {area}', '', '| ID | Stage | Feature and acceptance | B | U | I | UI handoff |', '|---|---|---|---|---|---|---|']
    for row in (r for r in rows if r['area'] == area):
        fid = row['id']
        deps = list(filter(None, row['depends_on'].split(',')))
        ready = backend_ready(fid)
        marks = ['[x]' if done[role, fid] else '[ ]' for role in ('backend', 'ui', 'integration')]
        if row['ui_required'] == 'no':
            marks[1] = 'n/a'
        handoff = 'Ready' if ready and row['ui_required'] == 'yes' else ('n/a' if row['ui_required'] == 'no' else 'Waiting for backend')
        if fid in review_required:
            handoff = 'Review required'
        acceptance = f"**{row['feature']}** — {row['acceptance']} Dependencies: {row['depends_on'] or 'none'}."
        lines.append(f"| {fid} | {row['stage']} | {acceptance} | {' | '.join(marks)} | {handoff} |")
    lines.append('')
(ROOT / 'docs/FEATURE_CHECKLIST.md').write_text('\n'.join(lines) + '\n')
print(f'Rendered {len(rows)} features; {sum(done["backend", r["id"]] for r in rows)} verified backend handoffs.')
